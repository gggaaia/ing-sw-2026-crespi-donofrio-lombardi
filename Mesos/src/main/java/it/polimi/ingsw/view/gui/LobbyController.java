package it.polimi.ingsw.view.gui;

import javafx.event.ActionEvent;
import javafx.fxml.FXML;
import javafx.geometry.Pos;
import javafx.scene.control.Label;
import javafx.scene.image.ImageView;
import javafx.scene.layout.HBox;
import javafx.scene.layout.VBox;
import javafx.scene.shape.Rectangle;

import java.util.List;

/**
 * Controller class for the game Lobby screen.
 * Handles the display of joined players and waiting slots.
 */
public class LobbyController {

    @FXML private ImageView sfondoPopup;
    @FXML private Label statusLabel;
    @FXML private VBox playersContainer;

    /**
     * Automatically called by JavaFX.
     * Initializes the UI elements, specifically applying a rounded clip to the background image.
     */
    @FXML
    public void initialize() {
        if (sfondoPopup != null) {
            Rectangle clip = new Rectangle(sfondoPopup.getFitWidth(), sfondoPopup.getFitHeight());
            clip.setArcWidth(40);
            clip.setArcHeight(40);
            sfondoPopup.setClip(clip);
        }
    }

    /**
     * Updates the lobby user interface with the current list of players and expected total.
     * @param joinedPlayers the list of nicknames currently in the lobby
     * @param expectedPlayers the total number of players required to start the game
     */
    public void updateLobbyData(List<String> joinedPlayers, int expectedPlayers) {
        int currentCount = joinedPlayers.size();

        if (statusLabel != null) {
            statusLabel.setText(String.format("Waiting for players... %d/%d", currentCount, expectedPlayers));
        }

        if (playersContainer != null) {
            playersContainer.getChildren().clear();

            // Slots for players who have already joined
            for (int i = 0; i < currentCount; i++) {
                playersContainer.getChildren().add(createPlayerRow(joinedPlayers.get(i), true));
            }

            // Empty slots
            for (int i = currentCount + 1; i <= expectedPlayers; i++) {
                playersContainer.getChildren().add(createPlayerRow("Waiting for Player " + i + "...", false));
            }
        }
    }

    /**
     * Creates an HBox representing a single row in the lobby (either a player or an empty slot).
     * @param text the text to display (nickname or waiting message)
     * @param isFull true if the slot contains a joined player, false if it is an empty waiting slot
     * @return the constructed HBox containing the player or slot information
     */
    private HBox createPlayerRow(String text, boolean isFull) {
        HBox row = new HBox();
        row.setSpacing(10);
        row.setAlignment(Pos.CENTER_LEFT);
        row.setPrefHeight(45);

        String bgColor = isFull ? "#562A2C" : "#2A2A2A";
        double opacity = isFull ? 1.0 : 0.4;

        row.setStyle(
                "-fx-background-color: " + bgColor + ";" +
                        "-fx-background-radius: 10;" +
                        "-fx-padding: 5 20 5 20;"
        );
        row.setOpacity(opacity);

        Label nameLabel = new Label(text);
        if (isFull) {
            nameLabel.setStyle("-fx-text-fill: #EFE4CB; -fx-font-family: \"Tempus Sans ITC\"; -fx-font-size: 20px; -fx-font-weight: bold;");
        } else {
            nameLabel.setStyle("-fx-text-fill: #EFE4CB; -fx-font-family: \"Tempus Sans ITC\"; -fx-font-size: 18px; -fx-font-style: italic;");
        }

        row.getChildren().add(nameLabel);

        return row;
    }

    /**
     * Handles the click event on the Leave button.
     * Aborts the lobby connection and returns the user to the Welcome screen.
     * @param event the action event generated by clicking the leave button
     */
    @FXML
    public void onLeaveClicked(ActionEvent event) {
        System.out.println("LOG: Player leaving the lobby. Returning to Welcome...");
        GuiView.abortLobbyAndDisconnect();
    }
}