package it.polimi.ingsw.view.gui;

import javafx.event.ActionEvent;
import javafx.fxml.FXML;
import javafx.scene.Node;
import javafx.scene.effect.BoxBlur;
import javafx.scene.effect.ColorAdjust;
import javafx.stage.Stage;
import javafx.application.Platform;

/**
 * Controller for the Welcome screen.
 * Applies the blur effect and delegates the opening of the popup to the GuiView.
 */
public class WelcomeController {

    /**
     * Handles the click event on the Start button.
     * Blurs and darkens the main window, then notifies the GuiView to unblock the flow.
     *
     * @param event the action event generated by clicking the Start button
     */
    @FXML
    public void onStartClicked(ActionEvent event) {

        // -- 1. BLUR AND DARKEN THE MAIN WINDOW --
        Stage mainStage = (Stage) ((Node) event.getSource()).getScene().getWindow();
        BoxBlur blur = new BoxBlur(10, 10, 3);
        ColorAdjust darken = new ColorAdjust();
        darken.setBrightness(-0.4); // 40% darker
        darken.setInput(blur);      // chain: blur first, then darken
        mainStage.getScene().getRoot().setEffect(darken);

        // Notifies the GuiView that Start has been clicked.
        // The GuiView itself will automatically call its method
        // openNicknamePopup() to safely load the popup window
        GuiView.notifyStartClicked();
    }
    /**
     * Handles the click event on the Exit button.
     * Completely closes the client application.
     *
     * @param event the action event generated by clicking the Exit button
     */
    @FXML
    public void onExitClicked(ActionEvent event) {
        Platform.exit();
        System.exit(0);
    }
}