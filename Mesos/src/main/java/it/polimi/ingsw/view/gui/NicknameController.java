package it.polimi.ingsw.view.gui;

import javafx.event.ActionEvent;
import javafx.fxml.FXML;
import javafx.scene.Node;
import javafx.scene.control.Label;
import javafx.scene.control.TextField;
import javafx.scene.image.ImageView;
import javafx.scene.shape.Rectangle;
import javafx.stage.Stage;

/**
 * Controller class for the Nickname Popup screen.
 * Handles the user input, image clipping, and server validation.
 */
public class NicknameController {

    @FXML
    private TextField nicknameField;

    @FXML
    private Label errorLabel;

    @FXML
    private ImageView sfondoPopup;

    /**
     * Automatically called when the popup opens.
     * Initializes elements, such as hiding the error badge and applying clipping.
     */
    @FXML
    public void initialize() {
        // Hides the red error badge when the popup opens
        errorLabel.setVisible(false);

        // Creates a rectangle with the same dimensions as the ImageView to clip it
        Rectangle clip = new Rectangle(sfondoPopup.getFitWidth(), sfondoPopup.getFitHeight());

        // Sets the rounding of the corners
        clip.setArcWidth(30);
        clip.setArcHeight(30);

        // Applies the clip to the ImageView
        sfondoPopup.setClip(clip);
    }

    /**
     * Method used by the GuiView to display a server error, if any.
     * * @param message the error message to display
     */
    public void showError(String message) {
        errorLabel.setText(message);
        errorLabel.setVisible(true);
    }

    /**
     * Handles the click event on the "Continue" button.
     * Validates the input and sends it to the server.
     * * @param event the action event generated by clicking the submit button
     */
    @FXML
    public void onSubmitClicked(ActionEvent event) {
        String nickname = nicknameField.getText().trim();

        // Hides any previous errors every time Submit is clicked
        errorLabel.setVisible(false);

        // Empty field check
        if (nickname.isEmpty()) {
            showError("Please enter a valid nickname!");
            return;
        }

        showError("Checking with server...");

        // Sends the name to the ClientController by completing the CompletableFuture.
        // The Server decides whether to accept or reject the name.
        GuiView.submitNickname(nickname);
    }

    /**
     * Handles the click event on the Close button.
     * Removes the blur effect from the main stage and closes the popup window.
     * * @param event the action event generated by clicking the close button
     */
    @FXML
    public void onCloseClicked(ActionEvent event) {
        // Finds the popup window
        Stage popupStage = (Stage) ((Node) event.getSource()).getScene().getWindow();

        // Finds the main screen (Welcome) and removes the blur effect
        Stage mainStage = (Stage) popupStage.getOwner();
        if (mainStage != null && mainStage.getScene() != null) {
            mainStage.getScene().getRoot().setEffect(null);
        }

        // Closes only the popup, leaving the game open
        popupStage.close();
    }
}