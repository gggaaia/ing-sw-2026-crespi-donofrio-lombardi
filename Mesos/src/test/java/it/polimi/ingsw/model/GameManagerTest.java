package it.polimi.ingsw.model;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Test class for the {@link GameManager} registry.
 * <p>
 * Verifies the core functionality of the server's top-level match registry,
 * ensuring that matches can be correctly created, retrieved by their unique ID,
 * and safely removed when finished.
 */
class GameManagerTest {

    private GameManager gameManager;

    /**
     * Initializes a fresh {@link GameManager} instance before each test execution
     * to ensure an isolated and empty registry.
     */
    @BeforeEach
    @DisplayName("Setup: Initialize an empty GameManager")
    void setUp() {
        gameManager = new GameManager();
    }

    /**
     * Verifies that creating a new match successfully generates a valid ID
     * and correctly stores the match in the internal registry so it can be retrieved.
     */
    @Test
    @DisplayName("Create Match: Instantiates, stores, and returns a valid Match ID")
    void testCreateMatch() {
        int newMatchID = gameManager.createMatch();

        assertTrue(newMatchID > 0, "The generated match ID should be strictly positive");

        Match retrievedMatch = gameManager.retrieveMatch(newMatchID);
        assertNotNull(retrievedMatch, "The created match should be successfully stored and retrievable");
        assertEquals(newMatchID, retrievedMatch.getMatchID(), "The retrieved match should have the identical ID");
    }

    /**
     * Verifies the retrieval mechanism when attempting to find a match ID
     * that does not exist in the registry (e.g., wrong ID or empty registry).
     */
    @Test
    @DisplayName("Retrieve Match: Returns null for non-existent match IDs")
    void testRetrieveMatch_NonExistent() {
        // Attempt to retrieve a match from an empty manager
        Match match = gameManager.retrieveMatch(999999);

        assertNull(match, "Retrieving a non-existent match should gracefully return null");
    }

    /**
     * Verifies that successfully closing an existing match removes it entirely
     * from the internal registry and returns true.
     */
    @Test
    @DisplayName("Close Match: Successfully removes an existing match")
    void testCloseMatch_ExistingMatch() {
        int matchID = gameManager.createMatch();

        // Ensure it's there before closing
        assertNotNull(gameManager.retrieveMatch(matchID));

        boolean isClosed = gameManager.closeMatch(matchID);

        assertTrue(isClosed, "closeMatch should return true when successfully removing an existing match");
        assertNull(gameManager.retrieveMatch(matchID), "The match should no longer be retrievable after being closed");
    }

    /**
     * Verifies that attempting to close a match that does not exist
     * safely returns false without causing errors.
     */
    @Test
    @DisplayName("Close Match: Safely returns false for non-existent match IDs")
    void testCloseMatch_NonExistentMatch() {
        boolean isClosed = gameManager.closeMatch(12345);

        assertFalse(isClosed, "closeMatch should return false if the match ID is not found in the registry");
    }

    /**
     * Verifies the registry's ability to handle multiple concurrent matches.
     * Ensures that retrieving and closing one specific match does not affect the others.
     */
    @Test
    @DisplayName("Concurrency Simulation: Handles multiple matches independently")
    void testMultipleMatchesHandling() throws InterruptedException {
        int id1 = gameManager.createMatch();
        // Pause to ensure different timestamp-based IDs are generated by the Match constructor
        Thread.sleep(5);
        int id2 = gameManager.createMatch();
        Thread.sleep(5);
        int id3 = gameManager.createMatch();

        assertNotEquals(id1, id2, "Match IDs must be unique");

        // Close the middle match
        boolean closedMiddle = gameManager.closeMatch(id2);

        assertTrue(closedMiddle, "Middle match should be successfully closed");
        assertNull(gameManager.retrieveMatch(id2), "Middle match should be removed");

        // Verify the other matches are completely unaffected
        assertNotNull(gameManager.retrieveMatch(id1), "First match must remain active");
        assertNotNull(gameManager.retrieveMatch(id3), "Third match must remain active");
    }
}